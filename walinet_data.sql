-- Index untuk dashboard dan pencarian.
CREATE INDEX IF NOT EXISTS pelanggan_owner_idx ON public.pelanggan(owner_id);
CREATE INDEX IF NOT EXISTS pelanggan_status_idx ON public.pelanggan(owner_id, status);
CREATE INDEX IF NOT EXISTS pembayaran_owner_date_idx ON public.pembayaran(owner_id, tanggal DESC);
CREATE INDEX IF NOT EXISTS voucher_owner_status_idx ON public.voucher(owner_id, status);
